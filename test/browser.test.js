const { test } = require('node:test')
const assert = require('node:assert/strict')
const { once } = require('node:events')
const { mkdirSync } = require('node:fs')
const { chromium } = require('playwright')
const { createApp } = require('../server/src/app')
const { startDatabase, stopDatabase } = require('../server/test/mongo')

test('browser: registered members, multiple payers, manager approvals and private payment actions', { timeout: 360000 }, async t=>{
  const uri = await startDatabase()

  const {app,db}=await createApp({database:{uri,name:'browser_test'},origin:'http://127.0.0.1:5199',authLimit:1000})
  const server=app.listen(5199,'127.0.0.1');await once(server,'listening')

  const browser=await chromium.launch({...(process.env.BROWSER_CHANNEL==='chromium'?{}:{channel:process.env.BROWSER_CHANNEL||'chrome'}),headless:true})
  const pages=[]
  t.after(async()=>{for(const [index,page] of pages.entries())if(!page.isClosed())await page.screenshot({path:`test-results/account-${index}.png`,fullPage:true,animations:'disabled',timeout:5000}).catch(()=>{});await browser.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));await db.close();await stopDatabase()})
  mkdirSync('test-results',{recursive:true})
  const errors=[]
  async function account(name,email) {
    const context=await browser.newContext({viewport:{width:1440,height:1000}}), page=await context.newPage()
    pages.push(page);page.setDefaultTimeout(20000)
    page.on('pageerror',e=>errors.push(e.message))
    await page.goto('http://127.0.0.1:5199')
    await page.getByRole('button',{name:'Create an account',exact:true}).click()
    await page.getByLabel('Your name').fill(name)
    await page.getByLabel('Email address').fill(email)
    await page.getByLabel('Password',{exact:true}).fill('browser-test-password')
    await page.getByRole('button',{name:'Create account',exact:true}).click()
    await page.getByRole('heading',{name:'Your next trip starts here'}).waitFor()
    return page
  }
  console.log('Browser: creating three accounts')
  const owner=await account('Manager Maya','manager@example.com')
  const friend=await account('Member Ali','ali@example.com')
  const third=await account('Member Sara','sara@example.com')
  const nav=(page,name)=>page.locator('.primary-nav').getByRole('button',{name,exact:true}).click()
  async function open(page) {
    await page.reload()
    await page.getByRole('heading',{name:/Welcome,/}).waitFor()
    await page.getByRole('button',{name:'Open trip',exact:true}).click()
    await page.getByRole('heading',{name:/Browser Weekend/}).waitFor()
  }
  async function find(page,email) {
    await page.getByLabel('Member email').fill(email)
    await page.getByRole('button',{name:'Find account',exact:true}).click()
    await page.locator('.selected-account').filter({hasText:email}).waitFor()
  }
  console.log('Browser: selecting registered trip members')
  await owner.getByRole('button',{name:'Create your first trip'}).click()
  await owner.getByLabel('Trip name',{exact:true}).fill('Browser Weekend')
  await owner.getByLabel('Destination').fill('Lake Tahoe')
  await find(owner,'ali@example.com')
  await owner.getByRole('dialog').getByRole('button',{name:'Create trip',exact:true}).click()
  await owner.getByRole('heading',{name:/Browser Weekend/}).waitFor()
  console.log('Browser: submitting multiple contributions')
  await open(friend)
  assert.equal(await friend.getByRole('button',{name:'Delete trip',exact:true}).count(),0)
  await friend.getByRole('button',{name:'Add an expense',exact:true}).first().click()
  await friend.getByLabel('What was this for?').fill('Shared dinner')
  await friend.getByLabel('Amount',{exact:true}).fill('100.00')
  await friend.getByLabel('Multiple people paid').check()
  await friend.getByLabel('Paid by You',{exact:true}).fill('60.00')
  await friend.getByRole('checkbox',{name:'Manager Maya',exact:true}).check()
  await friend.getByLabel('Paid by Manager Maya',{exact:true}).fill('40.00')
  await friend.getByRole('button',{name:'Submit for approval'}).click()
  await nav(friend,'My submissions (1)')
  await friend.getByRole('heading',{name:'Shared dinner',exact:true}).waitFor()
  assert.equal(await friend.getByRole('button',{name:'Approve expense'}).count(),0)
  await nav(friend,'Expenses')
  assert.equal(await friend.locator('.expense-row').count(),0)
  await open(owner)
  await owner.getByRole('button',{name:'Add members',exact:true}).first().click()
  await find(owner,'sara@example.com')
  await owner.getByRole('dialog').getByRole('button',{name:'Add members',exact:true}).click()
  await owner.locator('.member-line').getByText('Member Sara').waitFor()
  await nav(owner,'Approvals (1)')
  await owner.getByRole('heading',{name:'Shared dinner',exact:true}).waitFor()
  await owner.screenshot({path:'test-results/manager-approvals.png',fullPage:true,animations:'disabled'})
  await owner.getByRole('button',{name:'Approve expense',exact:true}).click()
  await owner.getByText('No expenses waiting for review.').waitFor()
  await nav(owner,'Expenses')
  await owner.locator('.expense-info').getByText('Shared dinner').waitFor()
  await open(friend)
  await nav(friend,'Expenses')
  await friend.locator('.expense-info').getByText('Shared dinner').waitFor()
  assert.equal(await friend.getByRole('button',{name:'Options for Shared dinner'}).count(),0)
  console.log('Browser: verifying recipient-only payment confirmation')
  await open(third)
  await nav(third,'Settle up')
  const plan=third.locator('.plan-row').filter({hasText:'Member Ali'})
  await plan.getByRole('button',{name:'Record payment'}).click()
  await third.getByLabel(/^How much did you send/).fill('20.00')
  await third.getByRole('button',{name:'I’ve sent this'}).click()
  await third.locator('.payment-state.awaiting').waitFor()
  assert.equal(await third.getByRole('button',{name:'Confirm received'}).count(),0)
  await open(owner)
  await nav(owner,'Settle up')
  await owner.locator('.payment-state.awaiting').waitFor()
  assert.equal(await owner.getByRole('button',{name:'Confirm received'}).count(),0)
  await open(friend)
  await nav(friend,'Settle up')
  await friend.getByRole('button',{name:'Confirm received'}).click()
  await friend.locator('.payment-state.confirmed').waitFor()
  await nav(friend,'Overview')
  await friend.getByRole('button',{name:'Add an expense',exact:true}).first().click()
  await friend.getByLabel('What was this for?').fill('Extra snacks')
  await friend.getByLabel('Amount',{exact:true}).fill('30.00')
  await friend.getByRole('button',{name:'Submit for approval'}).click()
  await open(owner)
  await nav(owner,'Approvals (1)')
  await owner.getByRole('button',{name:'Reject expense',exact:true}).click()
  await owner.locator('.review-status.rejected').waitFor()
  await open(friend)
  await nav(friend,'My submissions')
  await friend.getByRole('button',{name:'Edit submission',exact:true}).click()
  await friend.getByLabel('What was this for?').fill('Corrected snacks')
  await friend.getByRole('button',{name:'Save changes',exact:true}).click()
  await friend.locator('.review-status.pending').waitFor()
  await open(owner)
  await nav(owner,'Approvals (1)')
  await owner.getByRole('button',{name:'Approve expense',exact:true}).click()
  await nav(owner,'Dashboard')
  await owner.getByRole('heading',{name:'Latest approved expenses'}).waitFor()
  await owner.screenshot({path:'test-results/manager-dashboard.png',fullPage:true,animations:'disabled'})
  await friend.setViewportSize({width:390,height:844})
  await friend.reload()
  await friend.getByRole('heading',{name:/Welcome,/}).waitFor()
  await friend.screenshot({path:'test-results/member-dashboard-mobile.png',fullPage:true,animations:'disabled'})
  assert.ok(await friend.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile dashboard must not scroll horizontally')
  await friend.getByRole('button',{name:'Open trip',exact:true}).click()
  await friend.locator('.mobile-nav').getByRole('button',{name:'Expenses',exact:true}).click()
  await friend.getByRole('textbox',{name:'Search expenses'}).fill('nothing matches')
  await friend.getByText('No expenses match those filters.').waitFor()
  await owner.getByRole('button',{name:'Sign out',exact:true}).last().click()
  await owner.getByRole('heading',{name:'Welcome back'}).waitFor()
  await owner.getByLabel('Email address').fill('manager@example.com')
  await owner.getByLabel('Password',{exact:true}).fill('wrong-password')
  await owner.getByRole('button',{name:'Sign in',exact:true}).click()
  await owner.getByRole('alert').getByText('Email or password is incorrect.').waitFor()
  await owner.getByLabel('Password',{exact:true}).fill('browser-test-password')
  await owner.getByRole('button',{name:'Sign in',exact:true}).click()
  await owner.getByRole('heading',{name:/Welcome,/}).waitFor()
  console.log('Browser: ending trip, publishing a receipt, and verifying member access')
  await owner.getByRole('button',{name:'Open trip',exact:true}).click()
  await owner.getByRole('button',{name:'End trip',exact:true}).click()
  await owner.getByRole('button',{name:'Keep trip active',exact:true}).click()
  await owner.getByRole('button',{name:'End trip',exact:true}).click()
  await owner.getByRole('button',{name:'End trip and lock expenses',exact:true}).click()
  await owner.getByRole('button',{name:'Generate receipt',exact:true}).click()
  await owner.getByRole('link',{name:'View receipt',exact:true}).waitFor()
  assert.equal(await owner.getByRole('button',{name:'Add an expense',exact:true}).count(),0)
  const receiptPromise=owner.context().waitForEvent('page')
  await owner.getByRole('link',{name:'View receipt',exact:true}).click()
  const receipt=await receiptPromise
  pages.push(receipt);receipt.setDefaultTimeout(20000)
  receipt.on('pageerror',error=>errors.push(error.message))
  await receipt.getByRole('heading',{name:'Browser Weekend',exact:true}).waitFor()
  await receipt.getByText('Outstanding balances remain',{exact:true}).waitFor()
  await receipt.getByRole('heading',{name:'Member summary',exact:true}).waitFor()
  assert.ok((await receipt.locator('.receipt').innerText()).includes('PKR'))
  await receipt.screenshot({path:'test-results/trip-receipt-desktop.png',fullPage:true,animations:'disabled'})
  mkdirSync('tmp/pdfs',{recursive:true})
  await receipt.pdf({path:'tmp/pdfs/trip-receipt-preview.pdf',format:'A4',preferCSSPageSize:true,printBackground:true})
  await receipt.setViewportSize({width:390,height:844})
  await receipt.screenshot({path:'test-results/trip-receipt-mobile.png',fullPage:true,animations:'disabled'})
  assert.ok(await receipt.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'receipt page must fit mobile width')
  await friend.reload()
  await friend.getByRole('heading',{name:/Welcome,/}).waitFor()
  await friend.getByRole('button',{name:'Open trip',exact:true}).click()
  await friend.getByRole('link',{name:'View receipt',exact:true}).waitFor()
  assert.equal(await friend.getByRole('button',{name:'Generate updated receipt',exact:true}).count(),0)
  const shareContext=await browser.newContext(),sharedPage=await shareContext.newPage()
  pages.push(sharedPage);sharedPage.setDefaultTimeout(20000)
  await sharedPage.goto(receipt.url())
  await sharedPage.getByRole('heading',{name:'Welcome back',exact:true}).waitFor()
  await sharedPage.getByLabel('Email address').fill('ali@example.com')
  await sharedPage.getByLabel('Password',{exact:true}).fill('browser-test-password')
  await sharedPage.getByRole('button',{name:'Sign in',exact:true}).click()
  await sharedPage.getByRole('heading',{name:'Browser Weekend',exact:true}).waitFor()
  await sharedPage.getByRole('button',{name:'Copy share link',exact:true}).waitFor()
  await nav(owner,'Dashboard')
  console.log('Browser: verifying trip deletion confirmation and remaining trips')
  await owner.locator('.page-content').getByRole('button',{name:'Create a trip',exact:true}).click()
  await owner.getByLabel('Trip name',{exact:true}).fill('Keep Trip')
  await owner.getByRole('dialog').getByRole('button',{name:'Create trip',exact:true}).click()
  await owner.getByRole('heading',{name:/Keep Trip/}).waitFor()
  await owner.locator('.trip-item').filter({hasText:'Browser Weekend'}).click()
  await owner.getByRole('button',{name:'Delete trip',exact:true}).click()
  assert.equal(await owner.getByRole('button',{name:'Delete trip permanently'}).isDisabled(),true)
  await owner.getByLabel('Type trip name to confirm').fill('wrong name')
  assert.equal(await owner.getByRole('button',{name:'Delete trip permanently'}).isDisabled(),true)
  await owner.getByRole('button',{name:'Keep trip',exact:true}).click()
  await owner.getByRole('heading',{name:/Browser Weekend/}).waitFor()
  await owner.getByRole('button',{name:'Delete trip',exact:true}).click()
  await owner.getByLabel('Type trip name to confirm').fill('Browser Weekend')
  await owner.getByRole('button',{name:'Delete trip permanently'}).click()
  await owner.getByRole('heading',{name:/Welcome,/}).waitFor()
  await owner.locator('.portal-trip').getByRole('heading',{name:'Keep Trip',exact:true}).waitFor()
  assert.equal(await owner.locator('.trip-item').filter({hasText:'Browser Weekend'}).count(),0)
  await friend.reload()
  await friend.getByRole('heading',{name:'Your next trip starts here'}).waitFor()
  await owner.getByRole('button',{name:'Open trip',exact:true}).click()
  await owner.getByRole('button',{name:'Delete trip',exact:true}).click()
  await owner.getByLabel('Type trip name to confirm').fill('Keep Trip')
  await owner.getByRole('button',{name:'Delete trip permanently'}).click()
  await owner.getByRole('heading',{name:'Your next trip starts here'}).waitFor()
  assert.deepEqual(errors,[])
})
